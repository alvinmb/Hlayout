"""Netlist file export: write the nets from Session.extract_netlist() /
hlayout.core.netlist.extract_netlist() in a format another tool can
read.

Formats (picked from the file extension unless given explicitly):

  csv    .csv  one row per (net, ref_des, pin) -- net, ref_des, pin
  report .txt  readable report: design/cell/layers header, every net and
               its members, then the issues (open bond ends, unassigned
               and unresolved pins, nets with no pins) with locations
  kicad  .net  KiCad netlist (s-expression, "(export (version D) ...)")
               -- imports into KiCad Pcbnew / Eeschema
  tango  .tng  Tango / Protel netlist ([ component ] ( net ) blocks) --
               read by most PCB tools (Protel, Altium, OrCAD Layout,
               DipTrace, ...)

The two EDA formats need a component list: every placed instance with a
ref designator becomes a component, its cell name used as footprint and
value. Members with no ref designator, bonded die pads without a pin
number (RefDes.@x,y) and the UNASSIGNED pseudo-net are left out of the
EDA formats (they are listed in the report), since no other tool could
resolve them.
"""

import csv
import datetime
import os

FORMATS = {"csv": ".csv", "report": ".txt", "kicad": ".net", "tango": ".tng"}

FORMAT_LABELS = {
    "csv": "CSV (net, ref_des, pin)",
    "report": "Text report",
    "kicad": "KiCad netlist",
    "tango": "Tango / Protel netlist",
}


def format_for_path(path, fmt=None):
    if fmt:
        f = fmt.lower()
        if f not in FORMATS:
            raise ValueError(f"unknown netlist format {fmt!r} -- use one of {', '.join(FORMATS)}")
        return f
    ext = os.path.splitext(path)[1].lower()
    for f, e in FORMATS.items():
        if e == ext:
            return f
    if ext in (".pnet", ".protel"):
        return "tango"
    return "csv"


def components(library, cell_name):
    """{ref_des: cell_name} for every labelled placement in the hierarchy
    of `cell_name` (the immediate placement's label, as netlist pins are
    attributed)."""
    out = {}
    seen = set()

    def walk(name, depth):
        if depth > 64 or name not in library.cells:
            return
        for ref in library.cells[name].srefs:
            if ref.label and ref.label not in out:
                out[ref.label] = ref.cell_name
            key = ref.cell_name
            if key not in seen:
                seen.add(key)
                walk(ref.cell_name, depth + 1)

    walk(cell_name, 0)
    return out


def _good(p):
    return bool(p.ref_des) and not str(p.pin).startswith("@")


def _real(nets):
    return [n for n in nets if n.id != "UNASSIGNED"]


def write_csv(nets, path):
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["net", "ref_des", "pin"])
        for net in nets:
            if not net.pins:
                w.writerow([net.id, "", ""])
                continue
            for p in net.pins:
                w.writerow([net.id, p.ref_des, p.pin])


def _mm(v):
    return f"{v / 1000.0:.3f}"


def write_report(nets, path, design="", cell="", layers=None):
    real = _real(nets)
    L = [f"Netlist report -- {design}  (cell {cell})",
         f"Generated by HLayout {datetime.datetime.now():%Y-%m-%d %H:%M}"]
    if layers:
        L.append("Conductor layers: " + ", ".join(str(n) for n in layers))
    L += [f"Nets: {len(real)}", ""]
    for net in real:
        members = ", ".join(p.label() for p in net.pins) or "(no pins)"
        extra = []
        if getattr(net, "bonds", 0):
            extra.append(f"{net.bonds} bond(s)")
        if net.unresolved_count:
            extra.append(f"{net.unresolved_count} unresolved")
        L.append(f"{net.id:<8} {members}" + (f"   [{'; '.join(extra)}]" if extra else ""))
    issues = []
    for net in nets:
        if net.id == "UNASSIGNED":
            for p in net.pins:
                issues.append(("Unassigned pin", "-", p.label() + " -- pin on a layer not used", p.xy))
            continue
        for p in net.pins:
            if str(p.pin).startswith("@"):
                issues.append(("Unresolved", net.id, p.label() + " -- bonded pad has no pin number", p.xy))
            elif not p.ref_des:
                issues.append(("Unresolved", net.id, p.label() + " -- part has no ref-des", p.xy))
        for xy in getattr(net, "open_bond_ends", []):
            issues.append(("Open bond end", net.id, "wire bond end lands on nothing", tuple(xy)))
        if not net.pins and getattr(net, "location", None) is not None:
            issues.append(("No pins", net.id, "copper with no pins on it", net.location))
    L += ["", f"Issues: {len(issues)}"]
    for kind, nid, text, xy in issues:
        where = f"  @ {_mm(xy[0])}, {_mm(xy[1])} mm" if xy else ""
        L.append(f"  {kind:<15} {nid:<8} {text}{where}")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


def _q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_kicad(nets, path, comps, design="", cell=""):
    used = sorted({p.ref_des for n in _real(nets) for p in n.pins if _good(p)})
    L = ["(export (version D)",
         "  (design",
         f"    (source {_q(design)})",
         f"    (date {_q(datetime.datetime.now().strftime('%Y-%m-%d %H:%M'))})",
         f"    (tool {_q('HLayout')})",
         f"    (sheet (number 1) (name {_q('/' + cell)}) (tstamps /)))",
         "  (components"]
    for ref in used:
        cn = comps.get(ref, "")
        L.append(f"    (comp (ref {_q(ref)}) (value {_q(cn)}) (footprint {_q(cn)}))")
    L += ["  )", "  (nets"]
    code = 0
    for net in _real(nets):
        nodes = [p for p in net.pins if _good(p)]
        code += 1
        L.append(f"    (net (code {_q(code)}) (name {_q('/' + net.id)})")
        for p in nodes:
            L.append(f"      (node (ref {_q(p.ref_des)}) (pin {_q(p.pin)}))")
        L[-1] += ")"          # closes the (net ...) on its last line
    L += ["  )", ")"]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


def write_tango(nets, path, comps):
    used = sorted({p.ref_des for n in _real(nets) for p in n.pins if _good(p)})
    L = []
    for ref in used:
        cn = comps.get(ref, "")
        L += ["[", ref, cn, cn, "", "", "]"]
    for net in _real(nets):
        nodes = [p for p in net.pins if _good(p)]
        if not nodes:
            continue
        L += ["(", net.id] + [f"{p.ref_des}-{p.pin}" for p in nodes] + [")"]
    with open(path, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("\n".join(L) + "\n")


def write_netlist(nets, path, fmt=None, library=None, cell_name="", design="", layers=None):
    """Write `nets` to `path` in `fmt` (or the format its extension
    implies). Returns the format used."""
    f = format_for_path(path, fmt)
    comps = components(library, cell_name) if (library is not None and cell_name) else {}
    if f == "csv":
        write_csv(nets, path)
    elif f == "report":
        write_report(nets, path, design=design, cell=cell_name, layers=layers)
    elif f == "kicad":
        write_kicad(nets, path, comps, design=design, cell=cell_name)
    else:
        write_tango(nets, path, comps)
    return f
